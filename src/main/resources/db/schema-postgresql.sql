-- =====================================================================
--  ShopEase schema - PostgreSQL 13+ edition of schema.sql (same tables and columns)
--  Idempotent: safe to run on every start-up.
--  Differences from MySQL: identity columns instead of AUTO_INCREMENT, separate
--  CREATE INDEX statements, no ENGINE/CHARSET, no ON UPDATE CURRENT_TIMESTAMP
--  (OrderDao sets updated_at itself).
-- =====================================================================

CREATE TABLE IF NOT EXISTS users (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name     VARCHAR(120)  NOT NULL,
    email         VARCHAR(160)  NOT NULL,
    password_hash VARCHAR(100)  NOT NULL,
    phone         VARCHAR(20),
    role          VARCHAR(20)   NOT NULL DEFAULT 'CUSTOMER',
    active        BOOLEAN       NOT NULL DEFAULT TRUE,
    created_at    TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_users_email UNIQUE (email)
);

CREATE TABLE IF NOT EXISTS categories (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(80)  NOT NULL,
    slug        VARCHAR(80)  NOT NULL,
    description VARCHAR(500),
    CONSTRAINT uk_categories_slug UNIQUE (slug)
);

CREATE TABLE IF NOT EXISTS products (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_id BIGINT        NOT NULL,
    sku         VARCHAR(40)   NOT NULL,
    name        VARCHAR(160)  NOT NULL,
    brand       VARCHAR(80),
    description TEXT,
    price       DECIMAL(12,2) NOT NULL,
    mrp         DECIMAL(12,2) NOT NULL,
    stock       INT           NOT NULL DEFAULT 0,
    image_url   VARCHAR(500),
    rating      DECIMAL(2,1)  NOT NULL DEFAULT 0.0,
    featured    BOOLEAN       NOT NULL DEFAULT FALSE,
    active      BOOLEAN       NOT NULL DEFAULT TRUE,
    created_at  TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_products_sku UNIQUE (sku),
    CONSTRAINT fk_products_category FOREIGN KEY (category_id) REFERENCES categories (id),
    CONSTRAINT ck_products_stock CHECK (stock >= 0)
);
CREATE INDEX IF NOT EXISTS idx_products_category ON products (category_id);
CREATE INDEX IF NOT EXISTS idx_products_name ON products (name);

CREATE TABLE IF NOT EXISTS cart_items (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT    NOT NULL,
    product_id BIGINT    NOT NULL,
    quantity   INT       NOT NULL,
    added_at   TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_cart_user_product UNIQUE (user_id, product_id),
    CONSTRAINT fk_cart_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT fk_cart_product FOREIGN KEY (product_id) REFERENCES products (id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS orders (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_number   VARCHAR(30)   NOT NULL,
    user_id        BIGINT        NOT NULL,
    status         VARCHAR(20)   NOT NULL,
    subtotal       DECIMAL(12,2) NOT NULL,
    tax            DECIMAL(12,2) NOT NULL,
    shipping       DECIMAL(12,2) NOT NULL,
    total          DECIMAL(12,2) NOT NULL,
    payment_method VARCHAR(20)   NOT NULL,
    ship_name      VARCHAR(120)  NOT NULL,
    ship_phone     VARCHAR(20)   NOT NULL,
    ship_line1     VARCHAR(200)  NOT NULL,
    ship_line2     VARCHAR(200),
    ship_city      VARCHAR(80)   NOT NULL,
    ship_state     VARCHAR(80)   NOT NULL,
    ship_zip       VARCHAR(12)   NOT NULL,
    notes          VARCHAR(500),
    created_at     TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at     TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_orders_number UNIQUE (order_number),
    CONSTRAINT fk_orders_user FOREIGN KEY (user_id) REFERENCES users (id)
);
CREATE INDEX IF NOT EXISTS idx_orders_user ON orders (user_id);
CREATE INDEX IF NOT EXISTS idx_orders_status ON orders (status);

CREATE TABLE IF NOT EXISTS order_items (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id     BIGINT        NOT NULL,
    product_id   BIGINT        NOT NULL,
    product_name VARCHAR(160)  NOT NULL,
    unit_price   DECIMAL(12,2) NOT NULL,
    quantity     INT           NOT NULL,
    line_total   DECIMAL(12,2) NOT NULL,
    CONSTRAINT fk_items_order FOREIGN KEY (order_id) REFERENCES orders (id) ON DELETE CASCADE,
    CONSTRAINT fk_items_product FOREIGN KEY (product_id) REFERENCES products (id)
);

CREATE TABLE IF NOT EXISTS payments (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id        BIGINT        NOT NULL,
    transaction_ref VARCHAR(40)   NOT NULL,
    method          VARCHAR(20)   NOT NULL,
    amount          DECIMAL(12,2) NOT NULL,
    status          VARCHAR(20)   NOT NULL,
    card_last4      VARCHAR(4),
    card_brand      VARCHAR(20),
    upi_id          VARCHAR(80),
    message         VARCHAR(255),
    created_at      TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_payments_txn UNIQUE (transaction_ref),
    CONSTRAINT fk_payments_order FOREIGN KEY (order_id) REFERENCES orders (id) ON DELETE CASCADE
);
CREATE INDEX IF NOT EXISTS idx_payments_order ON payments (order_id);
